//! Static analysis for Soroban smart contracts.
//!
//! `soroban-analyzer` reads a contract's Rust source and reports patterns that are
//! known to be bugs *on Soroban specifically*, with the things general Rust tooling
//! cannot know: that `require_auth` is the only thing standing between a privileged
//! entrypoint and anyone who can pay for the call, that temporary storage is reclaimed
//! and persistent storage is not, that an invocation may read at most 200 ledger
//! entries, and that arithmetic on an amount traps rather than wrapping because
//! contracts deploy with overflow checks on.
//!
//! It is the static-analysis half of the Soroban Static Analysis & Fuzzing Toolkit,
//! and it is designed around one contribution at a time: **one detector per pull
//! request**, each with its own fixtures.
//!
//! # What a check needs to be a detector
//!
//! A detector is two files:
//!
//! * `src/detectors/<id>.rs` — a struct implementing [`Detector`], saying what shape to
//!   look for;
//! * `rules/<id>.json` — the rule metadata: title, severity, rationale, remediation,
//!   references, and **two source snippets, one that must trigger the rule and one that
//!   must not**.
//!
//! Neither file is optional, and the snippets are not documentation. The crate's tests
//! parse and run every rule's own examples on every commit, so a detector that fires on
//! its clean example, or not on its triggering one, fails the build. That is how the
//! contribution standard — *a detector with no fixture proving it fires, and one
//! proving it does not over-fire, is not mergeable* — is enforced rather than merely
//! written down.
//!
//! Neither file requires an edit to any shared list: the registry is generated at build
//! time from the contents of those two directories.
//!
//! # Use from a test
//!
//! ```
//! use soroban_analyzer::{Analyzer, SourceFile};
//!
//! let analyzer = Analyzer::embedded();
//! let file = SourceFile::parse(
//!     "contract.rs",
//!     r#"
//! # use soroban_sdk::{contract, contractimpl, Env, Symbol, Address};
//! #[contract]
//! pub struct Fee;
//! #[contractimpl]
//! impl Fee {
//!     // No authorization anywhere, and instance storage is written.
//!     pub fn set_fee_bps(env: Env, bps: u32) {
//!         env.storage().instance().set(&Symbol::new(&env, "fee"), &bps);
//!     }
//! }
//! # "#.to_owned(),
//! )
//! .expect("the fixture parses");
//!
//! let found = analyzer.check_file(&file);
//! assert!(found
//!     .findings
//!     .iter()
//!     .any(|finding| finding.rule == "soroban-missing-require-auth"));
//! ```
//!
//! # Grading, and the exit status
//!
//! A finding's severity, rationale and remediation come from its rule, never from the
//! detector that reported it, so adding a detector cannot quietly re-grade an existing
//! pattern. Severities run from [`Severity::Info`] to [`Severity::Critical`], and the
//! binary exits non-zero when a finding at or above a threshold is present.
//!
//! # Deliberate exceptions
//!
//! A pattern that is correct in context is excused in the code with a marker comment
//! next to it — see [`suppress`] — and suppressed findings are counted and reported
//! rather than dropped, so a run never quietly loses one.
//!
//! # Limits
//!
//! These are syntactic checks over parsed source. They do not evaluate types, do not
//! follow calls across files, and do not look at the compiled Wasm. Each rule's
//! rationale states what it assumes; where an assumption cannot be checked, the rule
//! says so instead of guessing.

